// ============================================================================
// GENERATE docs/PARAMETERS.md FROM THE CODE.
//
//   npx tsx scripts/tools/generate-parameters-page.ts            # write it
//   npx tsx scripts/tools/generate-parameters-page.ts --check    # compare only
//
// ⚠ THE PAGE IS OUTPUT, NEVER INPUT. Nothing reads docs/PARAMETERS.md; it is a
// rendering of src/data/pricingParameters.ts plus the few tables that file
// registers without relocating. Editing the page by hand is therefore always a
// mistake, and parameters-page-check is what makes that mistake loud instead of
// silent — see its header.
//
// ⚠ THE SECTIONS IT DOES NOT OWN ARE READ FROM WHERE THEY LIVE. The payout
// patterns and the claim and shock distributions are NOT in the parameters
// module — the first because its provenance notes belong with the data, the
// second because both are being replaced and move in later. They are imported
// here and rendered, so the page is complete even though the module is not the
// source for them. If one of those moves into the module, delete its block
// here; do not leave it rendered twice.
// ============================================================================

import { readFileSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

// ⚠ ESM, SO THERE IS NO __dirname. Derived the way every other tool in
// scripts/ derives it; a bare __dirname throws at load here.
const __dirname = path.dirname(fileURLToPath(import.meta.url));
import { PRICING_PARAMETER_SECTIONS, type ParameterEntry } from '../../src/data/pricingParameters';
import {
  PAID_DEVELOPMENT_PATTERN, INCURRED_DEVELOPMENT_PATTERN, pctUnpaid,
} from '../../src/data/paidDevelopmentPatterns';
import { SHOCK_CATALOG } from '../../src/data/shockCatalog';
import type { CoverageLine } from '../../src/types/simulation';

const PAGE = path.join(__dirname, '../../docs/PARAMETERS.md');
const LINES: CoverageLine[] = ['WC', 'GL', 'Property'];

function cell(v: number | string): string {
  if (typeof v === 'string') return v;
  return Number.isInteger(v) ? String(v) : String(v);
}

function row(name: string, e: ParameterEntry): string {
  const basis = e.notYetUsed ? `${e.basis} · not yet used` : e.basis;
  const what = e.note ? `${e.what} ${e.note}` : e.what;
  return `| ${name} | \`${cell(e.value)}\` | ${e.unit} | ${basis} | ${what} |`;
}

function build(): string {
  const out: string[] = [];
  out.push('# Pricing parameters');
  out.push('');
  out.push('⚠ **GENERATED. Do not edit this file.** It is rendered from');
  out.push('`src/data/pricingParameters.ts` by `scripts/tools/generate-parameters-page.ts`,');
  out.push('and `parameters-page-check` fails if the two disagree. To change a number,');
  out.push('change it in the module and regenerate.');
  out.push('');
  out.push('**SOURCED** means measured from the pool\'s own data or an external source named');
  out.push('in the note — changing it is a re-fit. **CHOSEN** means picked — changing it is a');
  out.push('decision. Entries marked *not yet used* are read by nothing today.');
  out.push('');

  for (const section of PRICING_PARAMETER_SECTIONS) {
    out.push(`## ${section.title}`);
    out.push('');
    if (section.blurb) { out.push(section.blurb); out.push(''); }
    out.push('| Parameter | Value | Unit | Basis | What it does |');
    out.push('| --- | --- | --- | --- | --- |');
    for (const [name, e] of section.entries) out.push(row(name, e));
    out.push('');
  }

  // ---- the payout patterns, read from where they live ---------------------
  out.push('## Payout patterns');
  out.push('');
  out.push('Read from `src/data/paidDevelopmentPatterns.ts`, which is where their provenance');
  out.push('notes live. **Recorded and not yet used** — they are intended to replace the fitted');
  out.push('Weibull payout curves when the simplified model is built, and nothing reads them.');
  out.push('');
  out.push('Age-to-ultimate factors, ground-up, ages in months from the START of the accident');
  out.push('year. GL is at a **limited layer whose limit was not supplied and must be added**');
  out.push('before wiring. WC\'s paid rows from 276 months are a **projected** tail, not measured.');
  out.push('');
  // ⚠ THE LAST COLUMN MEANS A DIFFERENT THING ON EACH BASIS, so it is named
  // for the basis rather than given one label that is right for half the
  // rows: 1 - 1/LDF is UNPAID on a paid factor and UNREPORTED on an
  // incurred one. The first draft called both "still unpaid".
  out.push('| Line | Basis | Rows | Ages | Ends at | Outstanding at the last age |');
  out.push('| --- | --- | --- | --- | --- | --- |');
  for (const l of LINES) {
    const paid = PAID_DEVELOPMENT_PATTERN[l];
    const inc = INCURRED_DEVELOPMENT_PATTERN[l];
    const pLast = paid[paid.length - 1];
    const iLast = inc[inc.length - 1];
    const proj = paid.filter(r => r.projected).length;
    const adj = inc.filter(r => r.adjusted).length;
    // The incurred row carries BOTH labels. WC's incurred table gained a
    // projected tail at pricing commit 5(c), so "projected" is no longer a
    // property only the paid patterns have, and a reader comparing the two
    // rows must be able to see which parts of each are measured.
    const iProj = inc.filter(r => r.projected).length;
    const incLabel = [iProj ? `${iProj} projected` : '', adj ? `${adj} adjusted` : '']
      .filter(Boolean).join(', ');
    out.push(`| ${l} | paid${proj ? ` (${proj} projected)` : ''} | ${paid.length} `
      + `| ${paid[0].ageMonths}–${pLast.ageMonths} | ${pLast.ldf} | ${(pctUnpaid(pLast.ldf) * 100).toFixed(1)}% unpaid |`);
    out.push(`| ${l} | incurred${incLabel ? ` (${incLabel})` : ''} | ${inc.length} `
      + `| ${inc[0].ageMonths}–${iLast.ageMonths} | ${iLast.ldf} | ${(pctUnpaid(iLast.ldf) * 100).toFixed(1)}% unreported |`);
  }
  out.push('');
  out.push('A pool-layer WC pattern also exists and is deliberately not used — the game\'s');
  out.push('losses are ground-up. The GL "Total" paid pattern is retired for showing more paid');
  out.push('than reported at eight ages, 108 through 192 months. A second WC tail extension');
  out.push('jumping to ~9.3% emergence at 264 months was rejected for breaking the data\'s trend.');
  out.push('');
  out.push('⚠ WC\'s incurred pattern is **measured to 264 months and projected from 276 to 444**,');
  out.push('continuing the last measured annual decline in the IBNR share (3.827%). Before this it');
  out.push('stopped at 264 while paid ran to 444, leaving the case/IBNR split undefined across the');
  out.push('gap; the split is now a derived presentation shown for every accident year, so the gap');
  out.push('had to close. All three lines\' incurred patterns now end where their paid patterns do.');
  out.push('');

  // ---- to be replaced ------------------------------------------------------
  out.push('## To be replaced by the new distributions');
  out.push('');
  out.push('Listed for completeness and read from their current locations. These are **not** in');
  out.push('the parameters module and are not moved by this commit — they are being replaced,');
  out.push('and they move in when their replacement lands.');
  out.push('');
  out.push('| What | Where it lives | Notes |');
  out.push('| --- | --- | --- |');
  out.push('| WC claim frequency and severity | `src/utils/wcClaimEngine.ts`, `src/data/defaultAssumptions.ts` | Per-component lognormal severity with named components. |');
  out.push('| GL claim frequency and severity | `src/utils/glClaimEngine.ts` | Severity drawn from a tilted categorical over statistical tiers. |');
  out.push('| Property claim and catastrophe model | `src/utils/propertyClaimEngine.ts` | Non-cat and cat components. |');
  out.push('| Development / IBNER law | `src/data/defaultAssumptions.ts` | Mean-one per-claim revision law. |');
  // ⚠ A Record, NOT AN ARRAY — `.length` on it reads undefined, which is how
  // the first generated page came to say "undefined live events".
  out.push(`| Shock catalog | \`src/data/shockCatalog.ts\` | ${Object.keys(SHOCK_CATALOG).length} catalog entries. |`);
  out.push('');

  return out.join('\n') + '\n';
}

const generated = build();

if (process.argv.includes('--check')) {
  let onDisk: string | null = null;
  try { onDisk = readFileSync(PAGE, 'utf8'); } catch { onDisk = null; }
  if (onDisk === generated) {
    console.log('docs/PARAMETERS.md matches the module.');
    process.exit(0);
  }
  console.log('docs/PARAMETERS.md DOES NOT MATCH what the module would generate.');
  if (onDisk === null) {
    console.log('  the page is missing entirely.');
  } else {
    const a = onDisk.split('\n'), b = generated.split('\n');
    let shown = 0;
    for (let i = 0; i < Math.max(a.length, b.length) && shown < 5; i++) {
      if (a[i] !== b[i]) {
        console.log(`  line ${i + 1}:`);
        console.log(`    on disk:   ${a[i] ?? '(end of file)'}`);
        console.log(`    generated: ${b[i] ?? '(end of file)'}`);
        shown++;
      }
    }
  }
  console.log('\nRegenerate with: npx tsx scripts/tools/generate-parameters-page.ts');
  process.exit(1);
}

writeFileSync(PAGE, generated);
console.log(`wrote ${PAGE} (${generated.split('\n').length} lines)`);
