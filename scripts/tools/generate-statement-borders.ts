// ============================================================================
// THE ANNUAL STATEMENT'S BORDERS, READ FROM THE TEMPLATE — a generator.
//
//   npx tsx scripts/tools/generate-statement-borders.ts
//
// Reads every cell's border in docs/Annual Statement Example.xlsx and writes
// src/utils/annualStatementBorders.ts: one entry per statement row, row 1 first,
// with the template's row 15 ("Profit and Contigency") removed and the rows below
// it closed up — the same cut TEMPLATE_ROWS makes. Each entry is the eight
// columns A to H, each a string of the sides that carry a line (L, R, T, B).
//
// ⚠ GENERATED, NEVER EDITED BY HAND: the app cannot read the template at run time,
// so the borders are carried as data — and annual-statement-template-check reads
// the template again and compares every cell of the downloaded file against it,
// so a table that drifted from the file fails there, not on a person's screen.
//
// Every border the template draws is THIN; the generator refuses any other
// style rather than encoding one it does not carry.
// ============================================================================
import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';
import ExcelJS from 'exceljs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const TEMPLATE = path.join(__dirname, '../../docs/Annual Statement Example.xlsx');
const OUT = path.join(__dirname, '../../src/utils/annualStatementBorders.ts');
/** The template's row removed from the statement: 15, "Profit and Contigency". */
export const REMOVED_TEMPLATE_ROW = 15;
const COLUMNS = 8; // A to H

/** Every template cell's border, as 'LRTB' sides: [row][col], 1-based rows, columns A..H. */
export async function templateBorders(file = TEMPLATE): Promise<{ rows: number; sides: string[][] }> {
  const wb = new ExcelJS.Workbook();
  await wb.xlsx.readFile(file);
  const ws = wb.worksheets[0];
  const rows = ws.rowCount;
  const sides: string[][] = [];
  for (let r = 1; r <= rows; r++) {
    const row: string[] = [];
    for (let c = 1; c <= COLUMNS; c++) {
      const b = ws.getCell(r, c).border ?? {};
      let s = '';
      for (const [k, side] of [['L', b.left], ['R', b.right], ['T', b.top], ['B', b.bottom]] as const) {
        if (!side?.style) continue;
        if (side.style !== 'thin') throw new Error(`template ${ws.getCell(r, c).address}: a ${side.style} border — only thin is carried`);
        s += k;
      }
      row.push(s);
    }
    sides.push(row);
  }
  return { rows, sides };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const { rows, sides } = await templateBorders();
  const kept = sides.filter((_, i) => i + 1 !== REMOVED_TEMPLATE_ROW);
  const body = kept.map((r, i) => {
    const tr = i + 1 < REMOVED_TEMPLATE_ROW ? i + 1 : i + 2;
    return `  [${r.map(s => `'${s}'`).join(', ')}], // ${i + 1}${tr !== i + 1 ? ` (template ${tr})` : ''}`;
  }).join('\n');
  fs.writeFileSync(OUT, `// ============================================================================
// GENERATED by scripts/tools/generate-statement-borders.ts from
// docs/Annual Statement Example.xlsx — DO NOT EDIT BY HAND.
//
// Each statement row's borders, row 1 first, columns A to H: the sides of each
// cell that carry a thin line (L left, R right, T top, B bottom). The template's
// row ${REMOVED_TEMPLATE_ROW} ("Profit and Contigency") is removed and the rows below it close up,
// as TEMPLATE_ROWS does. annual-statement-template-check holds the downloaded
// file to the template cell for cell, so this table cannot drift from it unseen.
// ============================================================================

export const STATEMENT_BORDERS: readonly (readonly string[])[] = [
${body}
];
`);
  console.log(`${rows} template rows read, ${kept.length} written (row ${REMOVED_TEMPLATE_ROW} removed) -> ${path.relative(process.cwd(), OUT)}`);
}
