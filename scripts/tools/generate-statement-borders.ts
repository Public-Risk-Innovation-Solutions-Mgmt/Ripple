// ============================================================================
// THE ANNUAL STATEMENT'S BORDERS, READ FROM THE TEMPLATE — a generator.
//
//   npx tsx scripts/tools/generate-statement-borders.ts
//
// Reads every cell's border on the Pool sheet of docs/Annual Statement Example
// v2.xlsx and writes src/utils/annualStatementBorders.ts: one entry per TEMPLATE
// row, row 1 first — the statement maps its own rows onto these (TEMPLATE_ROW_OF,
// one inserted row) and adds column I's lines where it has no All Years. Each
// entry is the nine columns A to I (I is All Years), each a string of the sides
// that carry a line (L, R, T, B).
//
// ⚠ GENERATED, NEVER EDITED BY HAND: the app cannot read the template at run time,
// so the borders are carried as data — and annual-statement-template-check reads
// the template again and compares every cell of the downloaded file against it,
// so a table that drifted from the file fails there, not on a person's screen.
//
// Every border the template draws is THIN; the generator refuses any other
// style rather than encoding one it does not carry.
// ============================================================================
import * as fs from 'fs';
import * as path from 'path';
import { fileURLToPath } from 'url';
import ExcelJS from 'exceljs';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const TEMPLATE = path.join(__dirname, '../../docs/Annual Statement Example v2.xlsx');
/** The sheet the template is: v2 also carries a WC sheet, a filled example of a line's. */
export const TEMPLATE_SHEET = 'Pool';
const OUT = path.join(__dirname, '../../src/utils/annualStatementBorders.ts');
const COLUMNS = 9; // A to I

/** Every template cell's border, as 'LRTB' sides: [row][col], 1-based rows, columns A..I. */
export async function templateBorders(file = TEMPLATE): Promise<{ rows: number; sides: string[][] }> {
  const wb = new ExcelJS.Workbook();
  await wb.xlsx.readFile(file);
  const ws = wb.getWorksheet(TEMPLATE_SHEET);
  if (!ws) throw new Error(`template: no "${TEMPLATE_SHEET}" sheet`);
  const rows = ws.rowCount;
  const sides: string[][] = [];
  for (let r = 1; r <= rows; r++) {
    const row: string[] = [];
    for (let c = 1; c <= COLUMNS; c++) {
      const b = ws.getCell(r, c).border ?? {};
      let s = '';
      for (const [k, side] of [['L', b.left], ['R', b.right], ['T', b.top], ['B', b.bottom]] as const) {
        if (!side?.style) continue;
        if (side.style !== 'thin') throw new Error(`template ${ws.getCell(r, c).address}: a ${side.style} border — only thin is carried`);
        s += k;
      }
      row.push(s);
    }
    sides.push(row);
  }
  return { rows, sides };
}

if (process.argv[1] && fileURLToPath(import.meta.url) === path.resolve(process.argv[1])) {
  const { rows, sides } = await templateBorders();
  const body = sides.map((r, i) => `  [${r.map(x => `'${x}'`).join(', ')}], // ${i + 1}`).join('\n');
  fs.writeFileSync(OUT, `// ============================================================================
// GENERATED by scripts/tools/generate-statement-borders.ts from the Pool sheet
// of docs/Annual Statement Example v2.xlsx — DO NOT EDIT BY HAND.
//
// Each TEMPLATE row's borders, row 1 first, columns A to I (I is All Years): the
// sides of each cell that carry a thin line (L left, R right, T top, B bottom).
// The statement's own lines are these through its deliberate differences
// (annualStatementTemplate.ts, cellBorders). annual-statement-template-check
// holds the downloaded file to the template cell for cell, so this table cannot
// drift from it unseen.
// ============================================================================

export const TEMPLATE_BORDERS: readonly (readonly string[])[] = [
${body}
];
`);
  console.log(`${rows} template rows read and written, ${COLUMNS} columns -> ${path.relative(process.cwd(), OUT)}`);
}
